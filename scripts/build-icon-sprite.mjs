/**
 * Builds public/icons.svg — one <symbol> per icon and weight — and
 * src/lib/icon-sprite.ts with a content hash for cache-busting.
 *
 * Why: rendering Phosphor icons as inline SVG put ~200 copies of icon path
 * data in every page's HTML (~150 kB on the homepage) and ~100 kB of icon
 * code in the main JavaScript bundle. With a sprite, each icon on the page
 * is a few bytes (<svg><use href="/icons.svg?v=…#name--weight"/></svg>) and
 * the sprite itself is downloaded once and cached for every page.
 *
 * The icon list lives in src/components/icon-names.ts (name → Phosphor
 * component name). Run automatically by `build:pages`.
 */
import fs from "node:fs";
import crypto from "node:crypto";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as P from "@phosphor-icons/react/dist/ssr";

const WEIGHTS = ["bold", "fill", "duotone"];
const src = fs.readFileSync("src/components/icon-names.ts", "utf8");
const block = /ICON_COMPONENTS = \{([\s\S]*?)\} as const/.exec(src);
if (!block) throw new Error("icon-names.ts: ICON_COMPONENTS not found");
const pairs = [...block[1].matchAll(/^\s*"?([a-z0-9_-]+)"?:\s*"([A-Za-z]+Icon)",/gm)];
if (pairs.length < 10) throw new Error(`icon-names.ts: only ${pairs.length} icons parsed`);

const symbols = [];
for (const [, name, comp] of pairs) {
  const Cmp = P[comp];
  if (!Cmp) throw new Error(`Phosphor has no ${comp} (icon "${name}")`);
  for (const weight of WEIGHTS) {
    const svg = renderToStaticMarkup(createElement(Cmp, { weight, size: 256 }));
    const inner = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"));
    symbols.push(`<symbol id="${name}--${weight}" viewBox="0 0 256 256">${inner}</symbol>`);
  }
}
const sprite = `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("")}</svg>\n`;
fs.writeFileSync("public/icons.svg", sprite);
const hash = crypto.createHash("sha256").update(sprite).digest("hex").slice(0, 10);
fs.writeFileSync(
  "src/lib/icon-sprite.ts",
  `// Generated by scripts/build-icon-sprite.mjs — do not edit.\nexport const ICON_SPRITE_VERSION = "${hash}";\n`,
);
console.log(
  `icons.svg: ${pairs.length} icons × ${WEIGHTS.length} weights, ${(sprite.length / 1024).toFixed(0)} kB (v=${hash})`,
);
